"""The agent layer: generated instruction files for the user's agent.

One canonical source, `instructions.md`, renders to every agent file, so
they cannot drift apart (D-11). Limits in the text come from the user's
profile, so the instructions and the validator always state the same number
(FINDINGS F19). `jobforge init` writes these into the workspace, since a user
who installed from PyPI never sees the repo (SOW A-18), and `init --refresh`
rewrites them after an upgrade or a profile change.
"""
from __future__ import annotations

import re
from importlib import resources

from ..errors import JobforgeError

AGENT_FILES = ("CLAUDE.md", "AGENTS.md")
GENERATED_HEADER = ("<!-- Generated by Jobforge from its built-in instructions. Do not "
                    "edit;\n     run `jobforge init --refresh` to regenerate. -->\n\n")
_PLACEHOLDER = re.compile(r"\{\{(\w+)\}\}")


def source_text() -> str:
    return resources.files(__package__).joinpath("instructions.md").read_text(encoding="utf-8")


def render(values: dict[str, object]) -> str:
    def sub(m: re.Match) -> str:
        key = m.group(1)
        if key not in values:
            raise KeyError(f"instructions.md uses {{{{{key}}}}} but no value was given")
        return str(values[key])
    return GENERATED_HEADER + _PLACEHOLDER.sub(sub, source_text())


def values_for(ws) -> dict[str, object]:
    """Values from the workspace profile, or defaults while the profile is
    still the empty starter."""
    from ..profile import Profile, load_profile
    try:
        profile = load_profile(ws)
    except JobforgeError:
        profile = Profile(name="")
    return {
        "name": profile.name or "the user",
        "cover_letter_max_words": profile.cover_letter_max_words,
        "page_limit": profile.page_limit,
        "ghost_after_days": profile.ghost_after_days,
        "dash_rule": ", with no em or en dashes" if profile.ban_dashes else "",
    }


def write_agent_files(ws) -> list[str]:
    text = render(values_for(ws))
    for name in AGENT_FILES:
        (ws.root / name).write_text(text, encoding="utf-8", newline="\n")
    return list(AGENT_FILES)
