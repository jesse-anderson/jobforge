"""The agent layer: generated instruction files for the user's agent.

One canonical source, `instructions.md`, renders to every agent file, so
they cannot drift apart (D-11). Limits in the text come from the user's
profile, so the instructions and the validator always state the same number
(FINDINGS F19). `jobforge init` writes these into the workspace, since a user
who installed from PyPI never sees the repo (SOW A-18), and `init --refresh`
rewrites them after an upgrade or a profile change.
"""
from __future__ import annotations

import hashlib
import re
from importlib import resources

from ..errors import JobforgeError

AGENT_FILES = ("CLAUDE.md", "AGENTS.md")
GENERATED_HEADER = ("<!-- Generated by Jobforge from its built-in instructions. Edit only "
                    "below the\n     \"Your notes\" line at the end; `jobforge init "
                    "--refresh` regenerates the rest. -->\n\n")
_PLACEHOLDER = re.compile(r"\{\{(\w+)\}\}")

# The user's own section (#33). Everything below this line survives a
# refresh. The hash fingerprints the generated part above it, so a refresh
# can tell whether someone edited that part, and back it up if so.
NOTES_MARKER = "Your notes: write below this line"
_NOTES_LINE = re.compile(rf"^<!-- {re.escape(NOTES_MARKER)}\..*?\(jobforge:([0-9a-f]+)\) -->\n?",
                         re.MULTILINE)
_LEADING_COMMENT = re.compile(r"\A\s*<!--.*?-->\s*", re.DOTALL)


def _fingerprint(generated: str) -> str:
    return hashlib.sha256(generated.rstrip().encode("utf-8")).hexdigest()[:12]


def _with_notes(generated: str, notes: str = "") -> str:
    return (f"{generated}\n<!-- {NOTES_MARKER}. `jobforge init --refresh` keeps everything "
            f"below it. (jobforge:{_fingerprint(generated)}) -->\n{notes}")


def source_text() -> str:
    return resources.files(__package__).joinpath("instructions.md").read_text(encoding="utf-8")


def _generated(values: dict[str, object]) -> str:
    def sub(m: re.Match) -> str:
        key = m.group(1)
        if key not in values:
            raise KeyError(f"instructions.md uses {{{{{key}}}}} but no value was given")
        return str(values[key])
    return GENERATED_HEADER + _PLACEHOLDER.sub(sub, source_text())


def render(values: dict[str, object]) -> str:
    """A fresh agent file: the generated text, then an empty notes section."""
    return _with_notes(_generated(values))


def values_for(ws) -> dict[str, object]:
    """Values from the workspace profile, or defaults while the profile is
    still the empty starter."""
    from ..profile import Profile, load_profile
    try:
        profile = load_profile(ws)
    except JobforgeError:
        profile = Profile(name="")
    return {
        "name": profile.name or "the user",
        "cover_letter_max_words": profile.cover_letter_max_words,
        "page_limit": profile.page_limit,
        "ghost_after_days": profile.ghost_after_days,
        "dash_rule": (", and no dashes of any kind in anything you write (em, en, "
                      "figure, minus, or other): use a plain hyphen (-) only where a "
                      "word needs one" if profile.ban_dashes else ""),
    }


def _split(old: str, body: str) -> tuple[str, bool]:
    """An existing agent file -> (the user's notes, whether the generated
    part was edited). A file from before the notes section (#33) counts as
    edited unless it is this version's text."""
    m = _NOTES_LINE.search(old)
    if m:
        return old[m.end():], _fingerprint(old[:m.start()]) != m.group(1)
    return "", _LEADING_COMMENT.sub("", old, count=1).rstrip() != body.rstrip()


def _free_backup(path):
    n = 1
    while True:
        bak = path.with_name(path.name + (".bak" if n == 1 else f".bak{n}"))
        if not bak.exists():
            return bak
        n += 1


def write_agent_files(ws) -> list[str]:
    """Write CLAUDE.md and AGENTS.md, keeping the user's notes section. An
    edit above it is never dropped silently: the old file is saved as
    <name>.bak (then .bak2, ...) first. Returns a notice per backup."""
    for name in AGENT_FILES:  # both checked before either is written (#65)
        ws.check_inside(ws.root / name)
    generated = _generated(values_for(ws))
    body = _LEADING_COMMENT.sub("", generated, count=1)
    notices = []
    for name in AGENT_FILES:
        path = ws.root / name
        notes = ""
        if path.exists():
            old = path.read_text(encoding="utf-8-sig")
            notes, edited = _split(old, body)
            if edited:
                bak = _free_backup(path)
                bak.write_text(old, encoding="utf-8", newline="\n")
                notices.append(
                    f"{name} had edits outside its notes section, so the old file is "
                    f"saved as {bak.name}. Move anything you want to keep below the "
                    f"\"Your notes\" line at the end of {name}.")
        path.write_text(_with_notes(generated, notes), encoding="utf-8", newline="\n")
    return notices
